import {readFileSync, writeFileSync} from 'node:fs';
const schema = JSON.parse(readFileSync(new URL('../backend/openapi.json', import.meta.url), 'utf8'));
function type(value) {
  if (value.$ref) return `ApiSchemas[${JSON.stringify(value.$ref.split('/').at(-1))}]`;
  if (value.const !== undefined) return JSON.stringify(value.const);
  if (value.enum) return value.enum.map(JSON.stringify).join(' | ');
  if (value.anyOf || value.oneOf) return (value.anyOf ?? value.oneOf).map(type).join(' | ');
  if (value.type === 'array') return `Array<${type(value.items ?? {})}>`;
  if (value.type === 'object' || value.properties) {
    if (!value.properties) return `Record<string, ${typeof value.additionalProperties === 'object' ? type(value.additionalProperties) : 'unknown'}>`;
    return `{ ${Object.entries(value.properties).map(([name, child]) => `${JSON.stringify(name)}${value.required?.includes(name) ? '' : '?'}: ${type(child)}`).join('; ')} }`;
  }
  return ({string:'string',integer:'number',number:'number',boolean:'boolean',null:'null'})[value.type] ?? 'unknown';
}
const output = '// Generated by scripts/generate-api-types.mjs; do not edit.\nexport interface ApiSchemas {\n' +
  Object.entries(schema.components.schemas).map(([name,value])=>`  ${JSON.stringify(name)}: ${type(value)};`).join('\n')+'\n}\n';
const target = new URL('../src/lib/api/generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target,'utf8') !== output) throw new Error('API types drift: run node scripts/generate-api-types.mjs');
} else writeFileSync(target,output);
